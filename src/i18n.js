  let current = 'es';

  function normalize(value) {
    return String(value === undefined || value === null ? '' : value);
  }

  // Traduce un texto exacto; si no hay traducción devuelve el original.
  function t(text, vars) {
    const source = normalize(text);
    if (!source) return source;
    const table = DICTIONARIES[current] || {};
    let translated = Object.prototype.hasOwnProperty.call(table, source) ? table[source] : source;
    if (vars) {
      Object.keys(vars).forEach((key) => {
        translated = translated.split(`{${key}}`).join(String(vars[key]));
      });
    }
    return translated;
  }

  function translateTextPreservingSpace(text) {
    const match = /^(\s*)([\s\S]*?)(\s*)$/.exec(text);
    if (!match) return text;
    const translated = t(match[2]);
    if (translated === match[2]) return text;
    return match[1] + translated + match[3];
  }

  const SKIP_TAGS = new Set(['SCRIPT', 'STYLE', 'TEXTAREA', 'CODE', 'PRE']);
  const ATTRS = ['placeholder', 'title', 'aria-label'];
  // Se recuerda el texto original de cada nodo para poder cambiar de idioma
  // sin acumular traducciones sobre traducciones.
  const ORIGINALS = new WeakMap();
  const ATTR_ORIGINALS = new WeakMap();

  function translateElement(element) {
    if (!element || SKIP_TAGS.has(element.tagName)) return;
    if (element.hasAttribute && element.hasAttribute('data-no-i18n')) return;
    if (element.closest && element.closest('[contenteditable="true"]')) return;
    // La capa de texto del PDF no se toca: pertenece al documento, no a la interfaz.
    if (element.closest && element.closest('.textLayer')) return;
    for (let i = 0; i < element.children.length; i += 1) {
      translateElement(element.children[i]);
    }
    for (let i = 0; i < element.childNodes.length; i += 1) {
      const node = element.childNodes[i];
      if (node.nodeType !== 3) continue;
      if (!ORIGINALS.has(node)) ORIGINALS.set(node, node.nodeValue);
      const next = translateTextPreservingSpace(ORIGINALS.get(node));
      if (next !== node.nodeValue) node.nodeValue = next;
    }
    if (element.hasAttribute) {
      ATTRS.forEach((name) => {
        if (!element.hasAttribute(name)) return;
        let map = ATTR_ORIGINALS.get(element);
        if (!map) {
          map = {};
          ATTR_ORIGINALS.set(element, map);
        }
        if (!(name in map)) map[name] = element.getAttribute(name);
        const next = translateTextPreservingSpace(map[name]);
        if (next !== element.getAttribute(name)) element.setAttribute(name, next);
      });
    }
  }

  function setLanguage(language) {
    current = DICTIONARIES[language] ? language : 'es';
    // El arabe se escribe de derecha a izquierda.
    if (typeof document !== 'undefined' && document.documentElement) {
      document.documentElement.dir = isRtl(current) ? 'rtl' : 'ltr';
      document.documentElement.lang = current === 'zhTW' ? 'zh-TW' : current;
    }
    return current;
  }

  function isRtl(language) {
    const item = LANGUAGES.find((entry) => entry.code === language);
    return !!(item && item.rtl);
  }

  function getLanguage() {
    return current;
  }

  function availableLanguages() {
    return LANGUAGES.slice();
  }

  const api = { t, setLanguage, getLanguage, isRtl, translateElement, availableLanguages, DICTIONARIES, LANGUAGES };
  root.ZeroPDFI18n = api;
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
